-- =============================================================================
-- Flyway Migration V1: Initial Schema for Beleza Total Clinic Management System
-- =============================================================================

-- ---------------------------------------------------------------------------
-- ENUMS
-- ---------------------------------------------------------------------------

CREATE TYPE categoria_procedimento AS ENUM ('FACIAL', 'CORPORAL', 'CAPILAR');

CREATE TYPE status_agendamento AS ENUM (
    'AGENDADO',
    'CONFIRMADO',
    'EM_ATENDIMENTO',
    'REALIZADO',
    'CANCELADO',
    'NAO_COMPARECEU'
);

CREATE TYPE perfil_usuario AS ENUM (
    'ADMIN',
    'ESTETICISTA_ADMINISTRADORA',
    'RECEPCIONISTA',
    'FUNCIONARIO'
);

CREATE TYPE dia_semana AS ENUM (
    'MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'
);

-- ---------------------------------------------------------------------------
-- TABLE: procedimentos
-- ---------------------------------------------------------------------------

CREATE TABLE procedimentos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(255)   NOT NULL,
    descricao       TEXT           NOT NULL,
    duracao_minutos INTEGER        NOT NULL,
    valor           NUMERIC(10, 2),
    categoria       categoria_procedimento NOT NULL,
    ativo           BOOLEAN        NOT NULL DEFAULT TRUE,
    imagem_url      VARCHAR(500),
    criado_em       TIMESTAMP      NOT NULL DEFAULT NOW(),
    atualizado_em   TIMESTAMP      NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- TABLE: funcionarios
-- ---------------------------------------------------------------------------

CREATE TABLE funcionarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(255)   NOT NULL,
    telefone        VARCHAR(255)   NOT NULL,
    cpf             VARCHAR(255)   NOT NULL UNIQUE,
    especialidade   VARCHAR(255),
    ativo           BOOLEAN        NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMP      NOT NULL DEFAULT NOW(),
    atualizado_em   TIMESTAMP      NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- TABLE: funcionario_procedimentos (Many-to-Many join)
-- ---------------------------------------------------------------------------

CREATE TABLE funcionario_procedimentos (
    funcionario_id  BIGINT NOT NULL REFERENCES funcionarios(id),
    procedimento_id BIGINT NOT NULL REFERENCES procedimentos(id),
    PRIMARY KEY (funcionario_id, procedimento_id)
);

-- ---------------------------------------------------------------------------
-- TABLE: horarios_atendimento
-- ---------------------------------------------------------------------------

CREATE TABLE horarios_atendimento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funcionario_id  BIGINT   NOT NULL REFERENCES funcionarios(id),
    dia_semana      dia_semana NOT NULL,
    hora_inicio     TIME    NOT NULL,
    hora_fim        TIME    NOT NULL,
    ativo           BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMP NOT NULL DEFAULT NOW(),
    atualizado_em   TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_horario_func_dia_hora UNIQUE (funcionario_id, dia_semana, hora_inicio)
);

-- ---------------------------------------------------------------------------
-- TABLE: clientes
-- ---------------------------------------------------------------------------

CREATE TABLE clientes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(255) NOT NULL,
    telefone              VARCHAR(255) NOT NULL,
    cpf                   VARCHAR(255) UNIQUE,
    email                 VARCHAR(255) UNIQUE,
    data_nascimento       DATE,
    observacoes           VARCHAR(255),
    ativo                 BOOLEAN      NOT NULL DEFAULT TRUE,
    consentimento_whatsapp BOOLEAN     NOT NULL DEFAULT FALSE,
    consentimento_dados   BOOLEAN      NOT NULL DEFAULT FALSE,
    data_consentimento    TIMESTAMP,
    criado_em             TIMESTAMP    NOT NULL DEFAULT NOW(),
    atualizado_em         TIMESTAMP    NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- TABLE: usuarios
-- ---------------------------------------------------------------------------

CREATE TABLE usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255)   NOT NULL UNIQUE,
    senha           VARCHAR(255)   NOT NULL,
    nome            VARCHAR(255)   NOT NULL,
    perfil          perfil_usuario NOT NULL,
    ativo           BOOLEAN        NOT NULL DEFAULT TRUE,
    funcionario_id  BIGINT         UNIQUE REFERENCES funcionarios(id),
    criado_em       TIMESTAMP      NOT NULL DEFAULT NOW(),
    atualizado_em   TIMESTAMP      NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- TABLE: agendamentos
-- ---------------------------------------------------------------------------

CREATE TABLE agendamentos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id      BIGINT             NOT NULL REFERENCES clientes(id),
    funcionario_id  BIGINT             NOT NULL REFERENCES funcionarios(id),
    procedimento_id BIGINT             NOT NULL REFERENCES procedimentos(id),
    data            DATE               NOT NULL,
    hora_inicio     TIME               NOT NULL,
    hora_fim        TIME               NOT NULL,
    status          status_agendamento NOT NULL,
    lembrete_enviado BOOLEAN           NOT NULL DEFAULT FALSE,
    criado_em       TIMESTAMP          NOT NULL DEFAULT NOW(),
    atualizado_em   TIMESTAMP          NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- INDEXES for agendamentos
-- ---------------------------------------------------------------------------

CREATE INDEX idx_agendamento_cliente          ON agendamentos (cliente_id);
CREATE INDEX idx_agendamento_funcionario      ON agendamentos (funcionario_id);
CREATE INDEX idx_agendamento_data             ON agendamentos (data);
CREATE INDEX idx_agendamento_status           ON agendamentos (status);
CREATE INDEX idx_agendamento_funcionario_data ON agendamentos (funcionario_id, data);

